export const LANGUAGES = [
  { code: 'en', label: 'English', locale: 'en-US' },
  { code: 'it', label: 'Italiano', locale: 'it-IT' },
];

let lang = 'en';

export function detectLanguage(stored) {
  if (stored && STRINGS[stored]) return stored;
  const nav = (typeof navigator !== 'undefined' && (navigator.languages?.[0] || navigator.language)) || 'en';
  return nav.toLowerCase().startsWith('it') ? 'it' : 'en';
}

export function setLanguage(code) {
  lang = STRINGS[code] ? code : 'en';
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}

export function getLanguage() {
  return lang;
}

export function localeFor(code = lang) {
  return LANGUAGES.find((l) => l.code === code)?.locale || 'en-US';
}

/** Translates a key, filling {placeholders}. Missing keys fall back to English, then the key. */
export function t(key, vars) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m));
  }
  return s;
}

/** Fills elements carrying data-i18n (text) inside root. */
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
}
